describe('dmath golden bits', () => {
  for (const [name, evaluate] of UNARY) {
    it(`returns the pinned bits for ${name} at its 32 fixed inputs`, () => {
      const pinned = GOLDEN[name];
      expect(pinned).toHaveLength(32);
      expect(pinned.map(([input]) => bitsHex(evaluate(input)))).toEqual(
        pinned.map(([, bits]) => bits)
      );
    });
  }

  it('returns the pinned bits for pow at its 32 fixed input pairs', () => {
    expect(GOLDEN.pow).toHaveLength(32);
    expect(GOLDEN.pow.map(([x, y]) => bitsHex(pow(x, y)))).toEqual(
      GOLDEN.pow.map((pair) => pair[2])
    );
  });
});
