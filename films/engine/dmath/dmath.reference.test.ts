type UnaryName = 'sin' | 'cos' | 'exp' | 'exp2' | 'log' | 'log2' | 'log10' | 'tanh';

type Reference = readonly [input: number, rounded: number, remainderUlps: number];

type PowReference = readonly [x: number, y: number, rounded: number, remainderUlps: number];

/**
 * Each function with its bound against the true value. tanh keeps fdlibm's
 * algorithm, whose own error reaches 1.95 ulp for |x| < 1, so it is held to 2.
 */
