describe('dmath against high-precision reference values', () => {
  for (const [name, evaluate, boundUlps] of UNARY) {
    it(`keeps ${name} within ${String(boundUlps)} ulp of the true value at every reference point`, () => {
      let worst = { ulps: 0, input: Number.NaN };
      for (const [input, rounded, remainderUlps] of REFERENCES[name]) {
        const ulps = errorUlps(evaluate(input), rounded, remainderUlps);
        if (ulps > worst.ulps) {
          worst = { ulps, input };
        }
      }
      expect(worst.ulps, `worst input ${String(worst.input)}`).toBeLessThanOrEqual(boundUlps);
    });
  }

  it('keeps pow within 1 ulp of the true value at every reference pair', () => {
    let worst = { ulps: 0, x: Number.NaN, y: Number.NaN };
    for (const [x, y, rounded, remainderUlps] of REFERENCES.pow) {
      const ulps = errorUlps(pow(x, y), rounded, remainderUlps);
      if (ulps > worst.ulps) {
        worst = { ulps, x, y };
      }
    }
    expect(worst.ulps, `worst input (${String(worst.x)}, ${String(worst.y)})`).toBeLessThanOrEqual(
      1
    );
  });
});
