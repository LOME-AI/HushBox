// dmath against the true values, so that no bound here rests on `Math`'s own
// accuracy. The points are the golden inputs plus each function's worst-case
// input against `Math` in the accuracy sweeps.
//
// Method: each true value was computed with Python's standard `decimal` module
// at 110 significant digits from the input's exact binary value. exp, ln and
// log10 are the module's own correctly rounded functions; log2 is ln(x)/ln(2),
// exp2 is exp(x·ln 2), and pow is exp(y·ln|x|) with the sign an odd integer
// exponent gives a negative base. sin and cos are Taylor series after
// reduction by π/2, with π from the series in the `decimal` documentation;
// tanh is the ratio of the sinh and cosh series. Each entry holds the true
// value's correctly rounded double, then the true value's distance from that
// double in ulps of the true value (0 below 1e-30 ulp).

